"""Writes app/src/main/kotlin/com/notivelo/app/look/LookPages.kt from the page-format corpus (tests/corpus/cases/<case>/expected.json).

    python apps/android-native/scripts/corpus-to-kotlin.py

The look scenes show corpus pages as the core returns them (`PageInfo.boxes`, `.content`): the same typed tree as
`readPage` makes from `page.bin`, written out as Kotlin (the JVM screenshot job has no host build of the core to call).
Ordered-list markers come from expected.json `orderedLists`. Run again when the corpus changes.
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
CASES = os.path.join(ROOT, "tests", "corpus", "cases")
OUT = os.path.join(ROOT, "apps", "android-native", "app", "src", "main", "kotlin", "com", "notivelo", "app", "look", "LookPages.kt")
USE = [("canvas-boxes", "canvasBoxes"), ("blocks", "blocks"), ("lists", "lists"), ("tasks", "tasks"), ("settings-and-ink", "settingsAndInk")]

KINDS = {
    "paragraph": "Paragraph", "heading": "Heading", "blockquote": "Blockquote", "codeBlock": "CodeBlock",
    "horizontalRule": "HorizontalRule", "hardBreak": "HardBreak", "bulletList": "BulletList", "orderedList": "OrderedList",
    "listItem": "ListItem", "taskList": "TaskList", "taskItem": "TaskItem", "taskRef": "TaskRef", "callout": "Callout",
    "details": "Details", "detailsSummary": "DetailsSummary", "detailsContent": "DetailsContent", "table": "Table",
    "tableRow": "TableRow", "tableCell": "TableCell", "tableHeader": "TableHeader", "image": "Image",
    "fileAttachment": "FileAttachment", "mention": "Mention", "pageLink": "PageLink",
}


def q(s):
    return json.dumps(s, ensure_ascii=True)


def mark(name, v):
    base = name.split("--")[0]
    if v is None:
        return None
    simple = {"bold": "Bold", "italic": "Italic", "underline": "Underline", "strike": "Strike", "code": "Code"}
    if base in simple:
        return "Mark." + simple[base]
    if base == "link":
        return "Mark.Link(%s)" % q((v or {}).get("href", ""))
    if base == "textStyle":
        return "Mark.TextColor(%s)" % q(v["color"]) if v.get("color") else None
    if base == "highlight":
        c = (v or {}).get("color")
        return "Mark.Highlight(%s)" % (q(c) if c else "null")
    if base == "comment":
        return "Mark.Comment(%s)" % q(v["threadId"])
    return "Mark.Unknown(%s)" % q(base)


def attr_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(float(v)) if isinstance(v, float) or True else str(v)
    if v is None:
        return "null"
    return q(str(v))


def node(n, frag, path, markers):
    if "text" in n:
        runs = []
        for r in n["text"]:
            ms = [m for m in (mark(k, v) for k, v in (r.get("attributes") or {}).items()) if m]
            runs.append("r(%s%s)" % (q(r["insert"]), "".join(", " + m for m in ms)))
        return "txt(%s)" % ", ".join(runs)
    if n.get("other"):
        return None
    tag = n["type"]
    kind = ("NodeKind." + KINDS[tag]) if tag in KINDS else "NodeKind.Unknown(%s)" % q(tag)
    at = dict(n.get("attrs", {}))
    if tag == "mention" and "id" in at:  # seed.ts: u1 is the demo user, any other id Sam
        at["id"] = "demo" if at["id"] == "u1" else "sam"
    attrs = ", ".join("a(%s, %s)" % (q(k), attr_value(v)) for k, v in sorted(at.items()))
    kids = []
    for i, c in enumerate(n.get("content", [])):
        k = node(c, frag, path + [i], markers)
        if k:
            kids.append(k)
    mk = markers.get((frag, tuple(path)), [])
    return "el(%s, listOf(%s), listOf(%s), listOf(%s))" % (
        kind, attrs, ", ".join(kids), ", ".join(q(m) for m in mk))


def main():
    out = ["// Generated by apps/android-native/scripts/corpus-to-kotlin.py from tests/corpus/cases/*/expected.json. Do not edit.",
           "package com.notivelo.app.look", "", "import com.notivelo.core.*", "",
           "/** Corpus pages as `readPage` returns them, for the look scenes. */", "internal object LookPages {"]
    for case, name in USE:
        e = json.load(open(os.path.join(CASES, case, "expected.json"), encoding="utf-8"))
        markers = {}
        for ol in e.get("orderedLists", []):
            markers[(ol["fragment"], tuple(ol["path"]))] = ol["markers"]
        order = e["readingOrder"]
        geoms = {b["id"]: b for b in e["boxes"]}
        boxes = []
        for bid in order:
            b = geoms[bid]
            boxes.append("PageBox(%s, %s, %s, %s, %s, %s)" % (
                q(bid), float(b["x"]), float(b["y"]), float(b["w"]), float(b["z"]), "true" if b.get("wide") else "false"))
        content = []
        for f in e["fragments"]:
            frag = f["name"]
            bid = None if frag == "default" else frag.split(":", 1)[1]
            nodes = [x for x in (node(c, frag, [i], markers) for i, c in enumerate(f["content"])) if x]
            content.append("BoxContent(%s, listOf(%s))" % (q(bid) if bid else "null", ",\n            ".join(nodes)))
        # fragments follow reading order after default
        s = e["pageSettings"]
        out.append("    val %s = LookPage(" % name)
        out.append("        boxes = listOf(%s)," % ", ".join(boxes))
        out.append("        content = listOf(%s)," % ",\n        ".join(content))
        out.append("        color = %s, rules = %s,\n    )" % (q(s["color"]), q(s["rules"])))
    out.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("corpus-to-kotlin:", OUT)


if __name__ == "__main__":
    main()
