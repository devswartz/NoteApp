// Converts docs/rewrite/look/icons/*.svg (Lucide, ISC licence) to one XAML path-data string per icon
// in Notivelo.Windows/Icons/IconData.cs. Run: node apps/windows/tools/gen-icons.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const dir = join(root, 'docs/rewrite/look/icons');
const attr = (tag, n) => { const m = new RegExp('(?:^|[ \t\r\n])' + n + '="([^"]*)"').exec(tag); return m ? m[1] : null; };
const num = (v, d = 0) => (v == null ? d : parseFloat(v));
const f = (n) => String(+n.toFixed(4));
const out = [];
for (const file of readdirSync(dir).filter((x) => x.endsWith('.svg')).sort()) {
  const svg = readFileSync(join(dir, file), 'utf8');
  const parts = [];
  for (const tag of svg.match(/<(path|circle|rect|line|polyline|ellipse|polygon)\b[^>]*>/g) ?? []) {
    const kind = /^<(\w+)/.exec(tag)[1];
    if (kind === 'path') {
      let d = attr(tag, 'd').trim();
      if (d[0] === 'm') {
        // The first moveto of a subpath is absolute; any further coordinate pairs are relative linetos.
        const mm = /^m\s*(-?\d*\.?\d+)[\s,]*(-?\d*\.?\d+)/.exec(d);
        let rest = d.slice(mm[0].length);
        if (/^[\s,]*[-.\d]/.test(rest)) rest = 'l' + rest;
        d = `M${mm[1]} ${mm[2]}` + rest;
      }
      parts.push(d);
    } else if (kind === 'circle' || kind === 'ellipse') {
      const cx = num(attr(tag, 'cx')), cy = num(attr(tag, 'cy'));
      const rx = num(attr(tag, kind === 'circle' ? 'r' : 'rx')), ry = kind === 'circle' ? rx : num(attr(tag, 'ry'));
      parts.push(`M${f(cx - rx)} ${f(cy)}A${f(rx)} ${f(ry)} 0 1 0 ${f(cx + rx)} ${f(cy)}A${f(rx)} ${f(ry)} 0 1 0 ${f(cx - rx)} ${f(cy)}Z`);
    } else if (kind === 'rect') {
      const x = num(attr(tag, 'x')), y = num(attr(tag, 'y')), w = num(attr(tag, 'width')), h = num(attr(tag, 'height'));
      let rx = num(attr(tag, 'rx')), ry = attr(tag, 'ry') != null ? num(attr(tag, 'ry')) : rx;
      if (rx === 0) parts.push(`M${f(x)} ${f(y)}H${f(x + w)}V${f(y + h)}H${f(x)}Z`);
      else parts.push(`M${f(x + rx)} ${f(y)}H${f(x + w - rx)}A${f(rx)} ${f(ry)} 0 0 1 ${f(x + w)} ${f(y + ry)}V${f(y + h - ry)}A${f(rx)} ${f(ry)} 0 0 1 ${f(x + w - rx)} ${f(y + h)}H${f(x + rx)}A${f(rx)} ${f(ry)} 0 0 1 ${f(x)} ${f(y + h - ry)}V${f(y + ry)}A${f(rx)} ${f(ry)} 0 0 1 ${f(x + rx)} ${f(y)}Z`);
    } else if (kind === 'line') {
      parts.push(`M${attr(tag, 'x1')} ${attr(tag, 'y1')}L${attr(tag, 'x2')} ${attr(tag, 'y2')}`);
    } else {
      const pts = attr(tag, 'points').trim().split(/[\s,]+/);
      let d = 'M' + pts[0] + ' ' + pts[1];
      for (let i = 2; i < pts.length; i += 2) d += 'L' + pts[i] + ' ' + pts[i + 1];
      parts.push(d + (kind === 'polygon' ? 'Z' : ''));
    }
  }
  out.push(`        ["${file.replace('.svg', '')}"] = "${parts.join(' ')}",`);
}
writeFileSync(join(root, 'apps/windows/Notivelo.Windows/Icons/IconData.cs'),
`// Generated by apps/windows/tools/gen-icons.mjs from docs/rewrite/look/icons (Lucide 1.68.0, ISC licence). Do not edit.
namespace Notivelo.Windows.Icons;

internal static class IconData
{
    public static readonly Dictionary<string, string> Paths = new()
    {
${out.join('\n')}
    };
}
`);
console.log(out.length, 'icons');
